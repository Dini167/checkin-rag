def pick_varied_message(messages: tuple[str, ...], times_used_before: int) -> str:
    """בוחרת ניסוח לפי הסדר, כדי שאותה הודעה לא תחזור פעמיים ברצף."""
    return messages[times_used_before % len(messages)]

