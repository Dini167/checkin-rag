def build_chunk_labels(chunk: KnowledgeChunk) -> str:
    """התגיות שמוצמדות לקטע: קהל היעד והאם הוא רגיש (README סעיפים 2, 5)."""
    labels = []
    if chunk.audience == Audience.TEAM_LEAD:
        labels.append(TEAM_LEAD_ONLY_LABEL)
    if chunk.sensitive:
        labels.append(SENSITIVE_LABEL)
    return " ".join(labels)


def format_numbered_chunks(chunks: list[KnowledgeChunk]) -> str:
    """ממספרת את הקטעים ומצמידה את התגיות, כדי שהמודל יוכל לצטט [1], [2]."""
    formatted_chunks = []
    for number, chunk in enumerate(chunks, start=1):
        labels = build_chunk_labels(chunk)
        title_line = f"[{number}] {labels}".rstrip()
        formatted_chunks.append(f"{title_line}\n{chunk.text}")
    return "\n\n".join(formatted_chunks)


def build_answer_prompt(
    question: str,
    role: UserRole,
    chunks: list[KnowledgeChunk],
    conversation_history: str,
) -> str:
    """בונה את הודעת המשתמש שנשלחת למודל התשובה."""
    return ANSWER_USER_MESSAGE_TEMPLATE.format(
        role_name=ROLE_DISPLAY_NAMES[role],
        conversation_history=conversation_history or "(אין)",
        numbered_chunks=format_numbered_chunks(chunks),
        question=question,
    )


